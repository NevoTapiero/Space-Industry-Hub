// Generates supabase/seed.sql from the researched data files, so the exact
// same content that ships in the bundle can be upserted into Supabase.
// Run: node scripts/gen-seed-sql.mjs

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const researchDir = join(root, 'src', 'data', 'research')
const outFile = join(root, 'supabase', 'seed.sql')

if (!existsSync(researchDir)) {
  console.error('No research data yet at', researchDir)
  process.exit(1)
}

const esc = (s) => s.replace(/'/g, "''")
const lines = ['-- Generated by scripts/gen-seed-sql.mjs. Run after schema.sql.', '']

for (const file of readdirSync(researchDir).sort()) {
  if (!file.endsWith('.json')) continue
  const doc = JSON.parse(readFileSync(join(researchDir, file), 'utf8'))
  if (file.startsWith('company-')) {
    lines.push(
      `insert into public.companies (slug, doc) values ('${esc(doc.slug)}', '${esc(JSON.stringify(doc))}') on conflict (slug) do update set doc = excluded.doc, updated_at = now();`,
    )
  } else if (file.startsWith('vehicle-')) {
    lines.push(
      `insert into public.vehicles (slug, doc) values ('${esc(doc.slug)}', '${esc(JSON.stringify(doc))}') on conflict (slug) do update set doc = excluded.doc, updated_at = now();`,
    )
  } else if (file === 'sources.json') {
    for (const vid of doc.videos || []) {
      lines.push(
        `insert into public.sources (video_id, doc) values ('${esc(vid.video_id)}', '${esc(JSON.stringify(vid))}') on conflict (video_id) do update set doc = excluded.doc, updated_at = now();`,
      )
    }
  }
}

writeFileSync(outFile, lines.join('\n') + '\n', 'utf8')
console.log('Wrote', outFile, `(${lines.length - 2} rows)`)
